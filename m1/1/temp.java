class temp {
    public static void main ( String [] args){
        int c=25;
        int f = (c*9/5)+32;
        System.out.println("Temperature in Fahrenheit: " +f);

        // To convert Fahrenheit to Celsius
        int f1 = 77;
        int c1 = (f1-32)*5/9;
        System.out.println("Temperature in Celsius: " +c1);
    } 
}